package ec.intercampus.intercampus;

import ec.intercampus.intercampus.service.BusService;
import ec.intercampus.intercampus.service.RouteService;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.boot.WebApplicationType;
import org.springframework.boot.builder.SpringApplicationBuilder;
import java.nio.file.Path;
import java.sql.DriverManager;
import java.util.List;
import static org.junit.jupiter.api.Assertions.*;

class LegacyDatabaseStartupTest {
    @TempDir Path directory;

    @Test
    void arrancaConBusesAntiguosYActualizaColumnasYEscenarioSinBorrarLaBase() throws Exception {
        String url = "jdbc:h2:file:" + directory.resolve("legacy");
        try (var connection = DriverManager.getConnection(url, "sa", "");
             var statement = connection.createStatement()) {
            for (String sql : """
                    CREATE TABLE rutas (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, codigo VARCHAR(255) UNIQUE NOT NULL, nombre VARCHAR(255) NOT NULL);
                    CREATE TABLE paradas (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nombre VARCHAR(255) NOT NULL, orden INTEGER NOT NULL, ruta_id BIGINT NOT NULL REFERENCES rutas(id), latitud DOUBLE NOT NULL, longitud DOUBLE NOT NULL);
                    CREATE TABLE buses (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, placa VARCHAR(255) UNIQUE NOT NULL, ruta_id BIGINT NOT NULL REFERENCES rutas(id), latitud DOUBLE NOT NULL, longitud DOUBLE NOT NULL, ultima_actualizacion TIMESTAMP WITH TIME ZONE NOT NULL);
                    CREATE TABLE arrival_records (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, route_id BIGINT NOT NULL, route_name VARCHAR(255) NOT NULL, bus_plate VARCHAR(255) NOT NULL, stop_name VARCHAR(255) NOT NULL, expected_arrival TIMESTAMP WITH TIME ZONE NOT NULL, actual_arrival TIMESTAMP WITH TIME ZONE NOT NULL);
                    INSERT INTO arrival_records (route_id,route_name,bus_plate,stop_name,expected_arrival,actual_arrival) VALUES (1,'Ruta Norte','BUS-001','Campus Norte',CURRENT_TIMESTAMP,CURRENT_TIMESTAMP);
                    INSERT INTO rutas (codigo,nombre) VALUES ('R-01','Ruta Norte'), ('R-02','Ruta Sur');
                    INSERT INTO paradas (nombre,orden,ruta_id,latitud,longitud) VALUES ('Terminal Terrestre',1,1,-2.17,-79.92), ('Facultad de Ingenieria',2,1,-2.18,-79.93), ('Campus Norte',3,1,-2.19,-79.94), ('Terminal Terrestre',1,2,-2.17,-79.92), ('Facultad de Derecho',2,2,-2.165,-79.915), ('Campus Sur',3,2,-2.155,-79.905);
                    INSERT INTO buses (placa,ruta_id,latitud,longitud,ultima_actualizacion) VALUES ('BUS-001',1,-2.17,-79.92,CURRENT_TIMESTAMP), ('BUS-002',2,-2.17,-79.92,CURRENT_TIMESTAMP);
                    """.split(";")) {
                if (!sql.isBlank()) statement.execute(sql);
            }
        }
        try (var context = new SpringApplicationBuilder(IntercampusApplication.class)
                .web(WebApplicationType.NONE).run("--spring.datasource.url=" + url,
                        "--spring.datasource.username=sa", "--spring.datasource.password=",
                        "--spring.jpa.hibernate.ddl-auto=update", "--tracker.enabled=false", "--demo.seed-enabled=true")) {
            var routes = context.getBean(RouteService.class).findAll();
            assertEquals(1, routes.size());
            assertEquals(List.of("Jipijapa", "UDLA Granados", "UDLA Park"),
                    routes.get(0).stops().stream().map(stop -> stop.name()).toList());
            var buses = context.getBean(BusService.class).findAll();
            assertEquals(3, buses.size());
            assertTrue(buses.stream().noneMatch(bus -> bus.manualControl()));
            var oldArrivals = context.getBean(ec.intercampus.intercampus.repository.ArrivalRecordRepository.class).findAll();
            assertEquals(1, oldArrivals.size());
            assertEquals(ec.intercampus.intercampus.domain.ArrivalSource.SIMULATED, oldArrivals.get(0).getSource());
            assertTrue(buses.stream().allMatch(bus -> bus.capacity() == 40));
            assertTrue(buses.stream().allMatch(bus -> bus.journey().arrival() != null));
        }
        try (var connection = DriverManager.getConnection(url, "sa", "");
             var statement = connection.createStatement();
             var result = statement.executeQuery("SELECT COUNT(*) FROM buses WHERE capacity = 40 AND next_stop_index >= 0")) {
            assertTrue(result.next());
            assertEquals(3, result.getInt(1));
        }
    }
}
